// FindAllPageable
//
// @Summary Get paginated list
// @Description Retrieves a paginated list using pagination parameters.
// @Tags purchases
// @Accept json
// @Produce json
// @Param page query int false "Page number (default: 1)"
// @Param size query int false "Number of items per page (default: 10)"
// @Param sort query string false "Sort order, e.g., 'name,asc'"
// @Success 200 {object} purchasesResponseList "Paginated list of Purchases"
// @Failure 400 {object} httputils.ErrorResponse "Bad Request (Invalid pagination parameters or service failure)"
// @Failure 500 {object} httputils.ErrorResponse "Internal Server Error (Data processing failure)"
// @Router /api/v1/purchases/pageable [get]
func (h *PurchasesHTTPHandler) FindAllPageable(w http.ResponseWriter, r *http.Request) {
	pq, err := pageable.GetPaginationFromCtx(r)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// call service
	resp, page, err := h.purchasesService.FindAllPageable(r.Context(), pq)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// convert service-model to handler-payload
	dtosToPayloads, err := mapDtosToPayloads(resp)
	if err != nil {
		httputils.WriteJSON(w, http.StatusInternalServerError, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// 200 OK
	httputils.WriteJSON(w, http.StatusOK, purchasesResponseList{
		Data: dtosToPayloads,
		Page: &page,
	})
}

// mappers

func mapCreateRequestToCreateInputDto(inputRequest *purchasesCreateRequest) (*dto.PurchasesCreateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between purchasesCreateRequest->PurchasesCreateDto")
	}
	return &dto.PurchasesCreateDto{
		CustomerID:  inputRequest.CustomerID,
		Description: inputRequest.Description,
	}, nil
}

func mapUpdateRequestToUpdateInputDto(inputRequest *purchasesUpdateRequest) (*dto.PurchasesUpdateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between purchasesUpdateRequest->PurchasesUpdateDto")
	}
	return &dto.PurchasesUpdateDto{
		CustomerID:  inputRequest.CustomerID,
		Description: inputRequest.Description,
	}, nil
}

func mapDtosToPayloads(inputDtos []dto.PurchasesDto) ([]purchasesResponse, error) {
	var outputResponses []purchasesResponse
	for _, inputDto := range inputDtos {
		toPayload, err := mapDtoToPayload(&inputDto)
		if err != nil {
			return nil, err
		}
		outputResponses = append(outputResponses, toPayload)
	}
	return outputResponses, nil
}

func mapDtoToPayload(inputDto *dto.PurchasesDto) (purchasesResponse, error) {
	if inputDto == nil {
		return purchasesResponse{}, fmt.Errorf("unexpected nil input for mapping between PurchasesDto->purchasesResponse")
	}
	return purchasesResponse{
		RecordID:    inputDto.RecordID,
		CustomerID:  inputDto.CustomerID,
		Description: inputDto.Description,
		CreatedAt:   inputDto.CreatedAt,
		UpdatedAt:   inputDto.UpdatedAt,
		Guid:        inputDto.Guid,
	}, nil
}
