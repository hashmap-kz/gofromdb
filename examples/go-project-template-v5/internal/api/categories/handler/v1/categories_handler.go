// FindAllPageable
//
// @Summary Get paginated list
// @Description Retrieves a paginated list using pagination parameters.
// @Tags categories
// @Accept json
// @Produce json
// @Param page query int false "Page number (default: 1)"
// @Param size query int false "Number of items per page (default: 10)"
// @Param sort query string false "Sort order, e.g., 'name,asc'"
// @Success 200 {object} categoriesResponseList "Paginated list of Categories"
// @Failure 400 {object} httputils.ErrorResponse "Bad Request (Invalid pagination parameters or service failure)"
// @Failure 500 {object} httputils.ErrorResponse "Internal Server Error (Data processing failure)"
// @Router /api/v1/categories/pageable [get]
func (h *CategoriesHTTPHandler) FindAllPageable(w http.ResponseWriter, r *http.Request) {
	pq, err := pageable.GetPaginationFromCtx(r)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// call service
	resp, page, err := h.categoriesService.FindAllPageable(r.Context(), pq)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// convert service-model to handler-payload
	dtosToPayloads, err := mapDtosToPayloads(resp)
	if err != nil {
		httputils.WriteJSON(w, http.StatusInternalServerError, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// 200 OK
	httputils.WriteJSON(w, http.StatusOK, categoriesResponseList{
		Data: dtosToPayloads,
		Page: &page,
	})
}

// mappers

func mapCreateRequestToCreateInputDto(inputRequest *categoriesCreateRequest) (*dto.CategoriesCreateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between categoriesCreateRequest->CategoriesCreateDto")
	}
	return &dto.CategoriesCreateDto{
		Name:        inputRequest.Name,
		ParentID:    inputRequest.ParentID,
		ValidPeriod: inputRequest.ValidPeriod,
	}, nil
}

func mapUpdateRequestToUpdateInputDto(inputRequest *categoriesUpdateRequest) (*dto.CategoriesUpdateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between categoriesUpdateRequest->CategoriesUpdateDto")
	}
	return &dto.CategoriesUpdateDto{
		Name:        inputRequest.Name,
		ParentID:    inputRequest.ParentID,
		ValidPeriod: inputRequest.ValidPeriod,
	}, nil
}

func mapDtosToPayloads(inputDtos []dto.CategoriesDto) ([]categoriesResponse, error) {
	var outputResponses []categoriesResponse
	for _, inputDto := range inputDtos {
		toPayload, err := mapDtoToPayload(&inputDto)
		if err != nil {
			return nil, err
		}
		outputResponses = append(outputResponses, toPayload)
	}
	return outputResponses, nil
}

func mapDtoToPayload(inputDto *dto.CategoriesDto) (categoriesResponse, error) {
	if inputDto == nil {
		return categoriesResponse{}, fmt.Errorf("unexpected nil input for mapping between CategoriesDto->categoriesResponse")
	}
	return categoriesResponse{
		RecordID:    inputDto.RecordID,
		Name:        inputDto.Name,
		ParentID:    inputDto.ParentID,
		ValidPeriod: inputDto.ValidPeriod,
		IsCurrent:   inputDto.IsCurrent,
		CreatedAt:   inputDto.CreatedAt,
		UpdatedAt:   inputDto.UpdatedAt,
		GUID:        inputDto.GUID,
	}, nil
}
