// FindAllPageable
//
// @Summary Get paginated list
// @Description Retrieves a paginated list using pagination parameters.
// @Tags currencies
// @Accept json
// @Produce json
// @Param page query int false "Page number (default: 1)"
// @Param size query int false "Number of items per page (default: 10)"
// @Param sort query string false "Sort order, e.g., 'name,asc'"
// @Success 200 {object} currenciesResponseList "Paginated list of Currencies"
// @Failure 400 {object} httputils.ErrorResponse "Bad Request (Invalid pagination parameters or service failure)"
// @Failure 500 {object} httputils.ErrorResponse "Internal Server Error (Data processing failure)"
// @Router /api/v1/currencies/pageable [get]
func (h *CurrenciesHTTPHandler) FindAllPageable(w http.ResponseWriter, r *http.Request) {
	pq, err := pageable.GetPaginationFromCtx(r)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// call service
	resp, page, err := h.currenciesService.FindAllPageable(r.Context(), pq)
	if err != nil {
		httputils.WriteJSON(w, http.StatusBadRequest, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// convert service-model to handler-payload
	dtosToPayloads, err := mapDtosToPayloads(resp)
	if err != nil {
		httputils.WriteJSON(w, http.StatusInternalServerError, httputils.ErrorResponse{Message: err.Error()})
		return
	}

	// 200 OK
	httputils.WriteJSON(w, http.StatusOK, currenciesResponseList{
		Data: dtosToPayloads,
		Page: &page,
	})
}

// mappers

func mapCreateRequestToCreateInputDto(inputRequest *currenciesCreateRequest) (*dto.CurrenciesCreateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between currenciesCreateRequest->CurrenciesCreateDto")
	}
	return &dto.CurrenciesCreateDto{
		CurrencyCode:  inputRequest.CurrencyCode,
		CurrencyValue: inputRequest.CurrencyValue,
	}, nil
}

func mapUpdateRequestToUpdateInputDto(inputRequest *currenciesUpdateRequest) (*dto.CurrenciesUpdateDto, error) {
	if inputRequest == nil {
		return nil, fmt.Errorf("unexpected nil input for mapping between currenciesUpdateRequest->CurrenciesUpdateDto")
	}
	return &dto.CurrenciesUpdateDto{
		CurrencyCode:  inputRequest.CurrencyCode,
		CurrencyValue: inputRequest.CurrencyValue,
	}, nil
}

func mapDtosToPayloads(inputDtos []dto.CurrenciesDto) ([]currenciesResponse, error) {
	var outputResponses []currenciesResponse
	for _, inputDto := range inputDtos {
		toPayload, err := mapDtoToPayload(&inputDto)
		if err != nil {
			return nil, err
		}
		outputResponses = append(outputResponses, toPayload)
	}
	return outputResponses, nil
}

func mapDtoToPayload(inputDto *dto.CurrenciesDto) (currenciesResponse, error) {
	if inputDto == nil {
		return currenciesResponse{}, fmt.Errorf("unexpected nil input for mapping between CurrenciesDto->currenciesResponse")
	}
	return currenciesResponse{
		RecordID:      inputDto.RecordID,
		CurrencyCode:  inputDto.CurrencyCode,
		CurrencyValue: inputDto.CurrencyValue,
		CreatedAt:     inputDto.CreatedAt,
		UpdatedAt:     inputDto.UpdatedAt,
		Guid:          inputDto.Guid,
	}, nil
}
